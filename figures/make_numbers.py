"""Every number the main text quotes from E6 and E1, as LaTeX macros read from the analysis outputs.

    python figures/make_numbers.py <records/icml directory> <split> > tex/numbers.tex

Macros are named \\N<Name>; intervals come as \\N<Name>Lo and \\N<Name>Hi. A development build marks every macro in
red so that it cannot be mistaken for a held-out number.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path


def fmt(x: float) -> str:
    return f"{x:.1f}".replace("-", "$-$")


def main(rec: str, split: str, e1_split: str | None = None) -> None:
    r = Path(rec)
    e1_split = e1_split or split
    e6 = json.loads((r / f"e6_results_v4_{split}.json").read_text())
    det = json.loads((r / f"e6det_results_v4_{split}.json").read_text())
    e1 = json.loads((r / f"e1_results_{e1_split}.json").read_text())
    tax = json.loads((r / f"e1_taxonomy_{e1_split}.json").read_text())
    out: dict[str, str] = {}

    def iv(name: str, m: dict | None) -> None:
        if not m or m.get("est") is None:
            out[name] = out[name + "Lo"] = out[name + "Hi"] = "n/a"
            return
        out[name], out[name + "Lo"], out[name + "Hi"] = fmt(m["est"]), fmt(m["lo"]), fmt(m["hi"])

    lv = e6["levels"]
    out["SixUnits"] = str(e6["n_units"])
    if split == "test":
        out["SixUnitsFirst"], out["SixUnitsSecond"] = "34", "7"       # frozen registration (e6.registered_units)
    out["SixControls"] = str(det["n_units"])
    out["SixReadings"] = f'{80 * e6["n_units"] + 16 * det["n_units"]:,}'.replace(",", "{,}")   # registered schedule
    iv("SixNoneFlag", lv["all|none"]["tpr"])           # equal to the false-flag rate by construction
    iv("SixNoneCov", lv["all|none"]["cov"])
    iv("SixMenuCov", lv["all|menu"]["cov"])
    iv("SixResolveCov", lv["all|resolve"]["cov"])
    iv("SixResolveFpr", lv["all|resolve"]["fpr"])
    up = lv["all|resolve"].get("fpr_betting_upper95")
    out["SixResolveFprUp"] = fmt(up) if up is not None else "n/a"
    iv("SixOne", e6["E6_1_cov_resolve_minus_menu"])
    iv("SixTwo", e6["E6_2_convention_advantage_none"])
    iv("SixFive", e6["E6_5_cov_sentence_minus_none"])
    iv("SixFlagPref", e6.get("flag_pref_a_minus_b_none"))     # Pr(flag | X_A) - Pr(flag | X_B), none arm
    iv("SixSentMinusRes", e6["sentence_minus_resolve_cov"])
    e63 = e6["E6_3_cov_high_minus_low_resolve"]
    iv("SixThree", e63)
    out["SixThreeBetLo"], out["SixThreeBetHi"] = ((fmt(e63["betting_lo"]), fmt(e63["betting_hi"]))
                                                  if "betting_lo" in e63 else ("n/a", "n/a"))
    v = e6["verdicts"]
    out["SixThreeVerdict"] = "within the margin" if v["E6_3_equivalent_within_10_claimed"] else "inconclusive"
    out["SixOneBVerdict"] = "met" if v["E6_1b_fpr_budget"] else "not met"
    rt = e6["routing_menu"]
    gpt = [rt[c] for c in rt if "gpt" in c]
    cla = [rt[c] for c in rt if "claude" in c]
    share = lambda xs, f: fmt(100 * sum(x[f] * x["n"] for x in xs) / sum(x["n"] for x in xs)) if sum(x["n"] for x in xs) else "n/a"
    out["SixGptPass"] = share(gpt, "pass")             # pooled over readings
    out["SixClaudeAsk"] = share(cla, "escalate")
    iv("SixFourJ", det["E6_4_J_none"])

    out["OneItems"], out["OneProblems"] = str(e1["n_items"]), str(e1["n_problems"])
    iv("OneHOne", e1["H1_vd_clause_minus_placebo"])
    iv("OneHFive", e1["H5_vd_clause_minus_pointer"])
    iv("OneHSix", tax["H6_vd_orig4_determined_minus_open"])
    tl = tax["levels"]
    iv("OneVdDetermined", tl.get("DETERMINED|defective|vd|orig4"))
    iv("OneVdOpen", tl.get("OPEN|defective|vd|orig4"))
    b = tax.get("bridge", {})
    out["OneBridgeItems"] = str(b.get("items_with_verified_diagnosis", "n/a"))
    out["OneBridgeDetermined"] = str(b.get("with_determined_witness", "n/a"))

    red = lambda s: r"\textcolor{red}{" + s + "}"
    print(f"% generated by figures/make_numbers.py from records/icml (E6 {split}, E1 {e1_split}); do not edit")
    for k, val in out.items():
        held_out = (e1_split if k.startswith("One") else split) == "test"
        print(rf"\newcommand{{\N{k}}}{{{val if held_out else red(val)}}}")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2], sys.argv[3] if len(sys.argv) > 3 else None)
